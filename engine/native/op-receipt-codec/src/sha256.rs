//! SHA-256 (FIPS 180-4), used only as the identity digest of a receipt
//! fingerprint. It is never a MAC, a key derivation or a password hash, and
//! nothing here depends on it being constant-time.
//!
//! It is written out here because no reviewed SHA-256 crate is available to
//! this offline build. It is checked against the FIPS 180-4 examples and
//! against Python `hashlib.sha256` in the vectors.

