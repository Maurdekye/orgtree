def anchors(repo: Path) -> dict[str, str]:
    return {p: hashlib.sha256((repo / p).read_bytes()).hexdigest() for p in ANCHORED}


def build(repo: Path) -> tuple[dict, str]:
    if sys.version_info[:2] != REQUIRED_PYTHON or os.name != "nt":
        raise SystemExit(f"run with the engine runtime Python {REQUIRED_PYTHON} on Windows, not {sys.version}")
    sys.path.insert(0, str(repo / "engine" / "backend"))
    from orgtree import ledger  # noqa: PLC0415

    if os.path.normcase is not ntpath.normcase or "_LCMapStringEx" not in ntpath.normcase.__code__.co_names:
        raise SystemExit("oracle stopped: ntpath.normcase is no longer LCMapStringEx; review the model")
    if ledger.TOOL_KEYS != ("bash", "web", "edit", "subagents") or \
            ledger.VIS_LEVELS != ("self", "team", "subtree", "full") or \
            ledger.PM_LEVELS != ("plan", "default", "acceptEdits", "bypassPermissions"):
        raise SystemExit("oracle stopped: ledger level constants moved; review the model")
    tables, stamp, lower = capture_tables(ledger)
    pool = char_pool(lower)
    rng = random.Random(20260923)
    normp, normc, reprs, strips = section_paths(rng, pool)
    nt, nd, em = section_norm(ledger, rng, pool)
    ct, cd = section_clamps(ledger, rng, pool)
    sc = Scratch(ledger)
    cv, ac, tc = section_ceiling(ledger, sc, rng, pool)
    doc: dict[str, Any] = {
        "schema": SCHEMA,
        "oracle": {"python": stamp["python"], "windows": stamp["windows"], "tables_sha256": stamp["sha256"],
                   "anchors": anchors(repo)},
        "limits": ("Synthetic inputs only. Expected values are current Python behavior on this Windows build, "
                   "not a new contract."),
        "normpath": normp, "normcase": normc, "repr": reprs, "strip": strips,
        "norm_tools": nt, "norm_dirs": nd, "expand_mcp": em,
        "clamp_tools": ct, "clamp_dirs": cd, "clamp_vis": cv,
        "apply_ceiling": ac, "tier_ceiling": tc,
    }
    return doc, tables


def render(doc: dict) -> str:
    """One row per line so a changed vector shows up as a readable diff."""
    parts = ["{"]
    keys = list(doc)
    for i, k in enumerate(keys):
        v = doc[k]
        tail = "," if i < len(keys) - 1 else ""
        if isinstance(v, list):
            parts.append(f" {json.dumps(k)}: [")
            for j, row in enumerate(v):
                sep = "," if j < len(v) - 1 else ""
                parts.append("  " + json.dumps(row, ensure_ascii=True, separators=(",", ":")) + sep)
            parts.append(" ]" + tail)
        else:
            parts.append(f" {json.dumps(k)}: " + json.dumps(v, ensure_ascii=True, separators=(",", ":")) + tail)
    parts.append("}")
    return "\n".join(parts) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--repo-root", type=Path, default=CRATE.parents[2])
    ap.add_argument("--vectors", type=Path, default=DEFAULT_VECTORS)
    ap.add_argument("--tables", type=Path, default=TABLES)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory(prefix="orgtree-scope-oracle-") as data:
        os.environ["ORGTREE_DATA"] = data
        doc, tables = build(args.repo_root.resolve())
    text = render(doc)
    digest = hashlib.sha256(text.encode()).hexdigest()
    if args.write:
        args.vectors.parent.mkdir(parents=True, exist_ok=True)
        args.vectors.write_text(text, encoding="utf-8", newline="\n")
        args.tables.write_text(tables, encoding="utf-8", newline="\n")
        print(f"wrote {args.vectors} ({len(text)} bytes, sha256 {digest}) and {args.tables}")
        return 0
    bad = []
    if args.vectors.read_text(encoding="utf-8") != text:
        bad.append(str(args.vectors))
    if args.tables.read_text(encoding="utf-8") != tables:
        bad.append(str(args.tables))
    if bad:
        print(f"MISMATCH: {', '.join(bad)} differ from what the current source and host produce")
        return 1
    print(f"matches: {args.vectors} ({len(text)} bytes, sha256 {digest}) and {args.tables}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
