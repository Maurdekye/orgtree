def check_known(msg: str) -> None:
    if msg.startswith(KNOWN_PREFIXES) or any(s in msg for s in KNOWN_INFIXES):
        return
    raise SystemExit(f"oracle stopped: unknown LedgerError pattern: {msg!r}")


# ---------------------------------------------------------------- encoding
def is_text(s: str) -> bool:
    return not any(0xD800 <= ord(c) < 0xE000 for c in s)


def enc(v: Any) -> Any:
    """A Python value as vector JSON: a str holding a lone surrogate becomes
    {"\\u0000str": [code points]}; dict keys must be text."""
    if isinstance(v, str):
        return v if is_text(v) else {PYSTR: [ord(c) for c in v]}
    if isinstance(v, bool) or v is None or isinstance(v, (int, float)):
        return v
    if isinstance(v, (list, tuple)):
        return [enc(x) for x in v]
    if isinstance(v, dict):
        for k in v:
            if not isinstance(k, str) or not is_text(k) or k == PYSTR:
                raise SystemExit(f"oracle stopped: dict key not encodable: {k!r}")
        return {k: enc(x) for k, x in v.items()}
    raise SystemExit(f"oracle stopped: value not encodable: {v!r}")


def run(call) -> dict:
    try:
        return {"ok": call()}
    except Exception as e:  # noqa: BLE001
        name = type(e).__name__
        if name == "LedgerError":
            check_known(str(e))
            return {"refused": enc(str(e))}
        return {"raises": name}


# ---------------------------------------------------------------- tables
def capture_tables(ledger) -> tuple[str, dict, list]:
    lower = []
    for c in range(MAXCP):
        if 0xD800 <= c < 0xE000:
            continue
        s = chr(c)
        a = ntpath.normcase(s)
        if a != s.replace("/", BS):
            if len(a) != 1:
                raise SystemExit(f"oracle stopped: normcase of U+{c:04X} is not 1:1")
            lower.append((c, ord(a)))
    nonprint, start = [], None
    for c in range(MAXCP + 1):
        bad = c < MAXCP and not chr(c).isprintable()
        if bad and start is None:
            start = c
        elif not bad and start is not None:
            nonprint.append((start, c - 1))
            start = None
    space = [c for c in range(MAXCP) if chr(c).isspace()]
    tiers = sorted(ledger.TIERS.items())
    blob = json.dumps({"lower": lower, "nonprint": nonprint, "space": space,
                       "tiers": tiers}, separators=(",", ":")).encode()
    stamp = {
        "windows": ".".join(map(str, sys.getwindowsversion()[:3])),
        "python": ".".join(map(str, sys.version_info[:3])),
        "normcase": "_winapi.LCMapStringEx(LOCALE_NAME_INVARIANT, LCMAP_LOWERCASE)",
        "sha256": hashlib.sha256(blob).hexdigest(),
        "lower": len(lower), "nonprintable_ranges": len(nonprint),
    }
    out = ["// @generated by oracle/generate_vectors.py --write. Do not edit.",
           "//!",
           "//! Case, printability and whitespace data of the engine runtime,",
           "//! captured by calling it. `NLS_LOWER` is what `ntpath.normcase`",
           "//! does to each code point (Windows NLS invariant lowercase via",
           "//! LCMapStringEx), NOT `str.lower()`.",
           "",
           f"pub const WINDOWS_BUILD: &str = {json.dumps(stamp['windows'])};",
           f"pub const PYTHON: &str = {json.dumps(stamp['python'])};",
           f"pub const TABLES_SHA256: &str = {json.dumps(stamp['sha256'])};",
           "",
           "/// (code point, lowercase) pairs, sorted; any other code point maps to itself.",
           "pub static NLS_LOWER: &[(u32, u32)] = &["]
    out += [f"    (0x{a:04x}, 0x{b:04x})," for a, b in lower]
    out += ["];", "",
            "/// Inclusive ranges of code points `str.isprintable()` rejects, sorted.",
            "pub static NONPRINTABLE: &[(u32, u32)] = &["]
    out += [f"    (0x{a:04x}, 0x{b:04x})," for a, b in nonprint]
    out += ["];", "",
            "/// `str.isspace()`, sorted.",
            f"pub static PY_WHITESPACE: [u32; {len(space)}] = ["]
    out += [f"    0x{c:04x}," for c in space]
    out += ["];", "",
            "/// `ledger.TIERS`: the static seat of each built-in tier.",
            "pub static TIERS: &[(&str, f64)] = &["]
    out += [f"    ({json.dumps(k)}, {float(v)!r})," for k, v in tiers]
    out += ["];", ""]
    return "\n".join(out), stamp, lower


# ---------------------------------------------------------------- string pools
def char_pool(lower: list[tuple[int, int]]) -> list[str]:
    diff = [0x130, 0x131, 0x1C5, 0x1C8, 0x1F2, 0x3A3, 0x3C2, 0x3F4, 0x1E9E, 0xDF, 0x212A,
            0x212B, 0x2126, 0x10400, 0x10428, 0x16E40, 0x1E900, 0xFF21, 0xFF41, 0x0130,
            0x0345, 0x0307, 0x0399, 0x03B9, 0x1FBE, 0x24B6, 0x2C00, 0xA7C0]
    pool = [chr(c) for c in diff] + [chr(a) for a, _ in lower[::7]] + [chr(b) for _, b in lower[::11]]
    pool += ["\ud800", "\udc00", "\udbff", "\udfff", "\ud801", "\x00", "\x7f", "\x85", "\xa0",
             "\u200b", "\u3000", "\t", "\n", " ", "'", '"', BS]
    return pool


def rand_path(rng: random.Random, pool: list[str]) -> str:
    parts = []
    r = rng.random()
    if r < 0.3:
        parts.append(rng.choice(["C:", "c:", "D:", "z:", "\u00e9:", "1:"]) + rng.choice([BS, "/", ""]))
    elif r < 0.45:
        parts.append(rng.choice([BS + BS, "//", BS + "/"]) + rng.choice(["srv", "SRV", "?", ".", "\u0130"]) +
                     rng.choice([BS, "/"]) + rng.choice(["share", "Sh", "UNC", "c:", ""]))
    elif r < 0.5:
        parts.append(rng.choice([BS + BS + "?" + BS + "UNC" + BS, "//?/unc/", BS + BS + "?" + BS + "C:", BS + BS + "." + BS]))
    elif r < 0.6:
        parts.append(rng.choice([BS, "/"]))
    for _ in range(rng.randint(0, 5)):
        k = rng.random()
        if k < 0.2:
            seg = rng.choice([".", "..", "...", ". ", " ..", ""])
        elif k < 0.6:
            seg = "".join(rng.choice(pool) for _ in range(rng.randint(1, 4)))
        else:
            seg = "".join(rng.choice("abcXYZ09_-") for _ in range(rng.randint(1, 5)))
        parts.append(seg + rng.choice([BS, "/", BS + BS, "", "/" + BS]))
    return "".join(parts)


