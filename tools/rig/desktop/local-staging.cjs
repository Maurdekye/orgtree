module.exports=async page=>{
  const attach=async(selector,name)=>{
    await page.eval((selector,name)=>{
      const input=document.querySelector(selector), dt=new DataTransfer()
      dt.items.add(new File([new Uint8Array(512*1024)],name,{type:'application/octet-stream'}))
      input.files=dt.files; input.dispatchEvent(new Event('change',{bubbles:true}))
    },selector,name)
  }
  await page.cdp('Network.enable')
  await page.cdp('Network.emulateNetworkConditions',{offline:false,latency:0,downloadThroughput:1024*1024,uploadThroughput:64*1024})
  await page.waitFor('.sq.orginbox'); await page.click('.sq.orginbox')
  await page.waitFor('.mailer-list .mailrow')
  await page.click({selector:'.mailer-list .mailrow *',text:'Reply staging target',regex:true})
  await page.waitFor('.mail-reply textarea')
  await page.click('.mail-reply textarea'); await page.type('Do not send before the file is ready')
  await attach('.mail-reply input[type=file]','reply.bin')
  await page.waitFor('.local-staging progress')
  await page.waitFor(()=>{const p=document.querySelector('.local-staging progress');return p?.value>0 && p.value<p.max})
  const replyBlocked=await page.eval(()=>document.querySelector('.mail-reply-send').disabled)
  if(!replyBlocked) throw Error('Reply not held during staging')
  await page.click('.mail-reply textarea'); await page.press('Enter')
  await page.screenshot('reply-staging')
  await page.waitFor('.attach-chip')
  await page.waitFor('.local-staging',{gone:true})
  if(await page.eval(()=>document.querySelector('.mail-reply-send').disabled)) throw Error('Reply stayed blocked after staging')
  await page.screenshot('reply-staged')
  await page.click({selector:'button',text:'compose mail'})
  await page.click({selector:'button',text:'other address…'})
  await page.click('input[placeholder="@net:slug / @org:slug"]'); await page.type('@org:test')
  await page.click('textarea[placeholder="the message…"]'); await page.type('Do not send while this file is pending')
  // The compose picker is the hidden multiple input in the topmost panel.
  const picker=await page.eval(()=>{ const inputs=[...document.querySelectorAll('input[type=file]')]; const p=inputs.at(-1); p.dataset.rigStagePicker='compose'; return '[data-rig-stage-picker="compose"]' })
  await attach(picker,'compose.bin')
  await page.waitFor('.local-staging progress')
  const composeBlocked=await page.eval(()=>[...document.querySelectorAll('button.primary')].find(b=>b.innerText.trim()==='send')?.disabled)
  if(!composeBlocked) throw Error('Compose not held during staging')
  await page.click('textarea[placeholder="the message…"]'); await page.press('Enter')
  await page.screenshot('compose-staging')
  await page.click({selector:'.local-staging button',text:'Cancel upload'})
  await page.waitFor('[data-stage-state="cancelled"]')
  await page.screenshot('compose-cancelled-held')
  await page.click({selector:'.local-staging button',text:'Retry file'})
  await page.waitFor('.local-staging',{gone:true})
  await page.screenshot('compose-staged')
  await page.cdp('Page.reload')
  await page.waitFor('.sq.orginbox'); await page.click('.sq.orginbox')
  await page.click({selector:'button',text:'compose mail'})
  await page.click({selector:'button',text:'other address…'})
  await page.click('input[placeholder="@net:slug / @org:slug"]'); await page.type('@org:test')
  await page.click({selector:'.saved-local-files > button',text:'Saved local files'})
  await page.waitFor(()=>[...document.querySelectorAll('[data-saved-file]')].some(x=>x.innerText.includes('compose.bin') && x.innerText.includes('Attach saved file')))
  await page.eval(()=>{
    const row=[...document.querySelectorAll('[data-saved-file]')].find(x=>x.innerText.includes('compose.bin') && x.innerText.includes('Attach saved file'))
    row.querySelector('button').click()
  })
  await page.waitFor(()=>[...document.querySelectorAll('.badge.free')].some(x=>x.innerText.includes('compose.bin') && x.innerText.includes('Attach saved file')))
  await page.eval(()=>[...document.querySelectorAll('.badge.free')].find(x=>x.innerText.includes('compose.bin')).scrollIntoView({block:'nearest'}))
  await page.screenshot('recovered-after-reload')
  return {replyBlocked,composeBlocked,retryCompleted:true,recoveredAfterReload:true}
}
