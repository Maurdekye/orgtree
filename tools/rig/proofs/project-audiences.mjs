import { Proof } from '../proof.mjs'

export default async function(rig){
  const p=new Proof('project-audiences')
  const hire=(name,parent,grant=0)=>rig.op({op:'hire',name,parent,tier:'haiku',grant,charter:'Synthetic project audience fixture.'})
  await hire('boss','user',200)
  await hire('manager','boss',80)
  await hire('peer-manager','boss',40)
  await rig.op({op:'create_project',name:'alpha',parent:'manager'})
  await rig.op({op:'create_project',name:'beta',parent:'peer-manager'})
  await rig.op({op:'create_project',name:'nested',parent:'alpha'})
  await hire('member','alpha',8)
  await hire('child','member')
  await hire('nested-member','nested')
  await hire('outsider','boss')
  await rig.waitFor(()=>rig.sql('SELECT 1 FROM ot.turns WHERE ended_at IS NULL').length===0,{what:'fixture idle',timeout:60000})
  const api=(action,node,target)=>rig.api('POST',`/api/orgs/${rig.org}/audiences`,{action,node,target,reason:'Synthetic audience proof'}).then(json=>({ok:true,json}),e=>({ok:false,error:String(e.body?.detail??e.message)}))
  const tool=(who,action,args={})=>rig.tool(who,'orgtree_audience',{action,...args})
  const userMail=who=>rig.tool(who,'orgtree_message',{to:'user',body:'Synthetic inherited audience check',notice:true})
  const explicitCount=who=>rig.one(`SELECT count(*)::int AS n FROM ot.audiences WHERE grantee='${who}' AND revoked_at IS NULL AND NOT paused`).n
  const grant=await api('grant','alpha','user')
  p.check('project user grant is accepted',grant.ok,grant)
  const agentGrant=await api('grant','alpha','outsider')
  p.check('project holds an audience with an agent',agentGrant.ok,agentGrant)
  const projectGrant=await api('grant','alpha','beta')
  p.check('both grant endpoints may be projects',projectGrant.ok,projectGrant)
  const direct=await userMail('member')
  p.check('direct member can write user through project audience',direct.ok,direct)
  const personal=await rig.tool('member','orgtree_present',{title:'Inherited personal presentation',body:'# Synthetic'})
  p.check('direct member can present personally through project audience',personal.ok,personal)
  const ask=await rig.tool('member','orgtree_ask',{question:'Synthetic inherited-audience question'})
  const askRow=rig.one("SELECT count(*)::int AS n FROM ot.asks q JOIN ot.agents a ON a.id=q.agent_id WHERE a.name='member' AND q.status='open'")
  p.check('direct member can ask user through project audience',ask.ok&&askRow?.n===1,{ask,askRow})
  const toAgent=await rig.tool('member','orgtree_message',{to:'outsider',body:'Synthetic project-to-agent audience',notice:true})
  const toProject=await rig.tool('member','orgtree_message',{to:'beta',body:'Synthetic project-to-project audience',notice:true})
  p.check('member inherits project audience with another agent',toAgent.ok,toAgent)
  p.check('member inherits project audience with another project',toProject.ok,toProject)
  p.check('inheritance stores no per-member grant rows',explicitCount('member')===0,{count:explicitCount('member')})
  for(const who of ['child','nested-member','outsider']){
    const no=await userMail(who)
    p.check(who+' does not inherit through a nested project or agent',!no.ok,no)
  }
  const tree=await rig.api('GET',`/api/orgs/${rig.org}`)
  const find=(rows,id)=>{for(const n of rows??[]){if(n.id===id)return n;const v=find(n.children,id);if(v)return v}}
  const body=find(tree.roots,'member')
  p.check('tree exposes effective audience and source project',body?.audiences_held?.includes('@user')&&JSON.stringify(body.audiences_inherited??[]).includes('alpha'),body)
  const chart=await rig.tool('boss','orgtree_chart',{})
  const inspect=await rig.tool('boss','orgtree_state_inspect',{node:'member'})
  p.check('chart reports inherited audience provenance',chart.ok&&/inherited/i.test(chart.text)&&/alpha/.test(chart.text),chart)
  p.check('state_inspect reports inherited audience provenance',inspect.ok&&/inherited/i.test(inspect.text)&&/alpha/.test(inspect.text),inspect)
  await rig.op({op:'move',node:'member',new_parent:'boss'})
  const moved=await userMail('member')
  p.check('moving out removes effective audience immediately',!moved.ok,moved)
  await rig.op({op:'move',node:'member',new_parent:'alpha'})
  const returned=await userMail('member')
  p.check('moving in restores effective audience without copying grants',returned.ok&&explicitCount('member')===0,returned)
  const own=await api('grant','member','user')
  const revoked=await api('revoke','alpha','user')
  const overlap=await userMail('member')
  p.check('own grant survives revoking project grant',own.ok&&revoked.ok&&overlap.ok,{own,revoked,overlap})
  await api('revoke','member','user')
  const gone=await userMail('member')
  p.check('revoking own and project grants removes permission',!gone.ok,gone)
  const forbidden=await tool('member','grant',{from:'child',target:'alpha'})
  const forbiddenRequest=await tool('member','request',{from:'alpha',target:'user'})
  p.check('direct member cannot manage project grant decisions',!forbidden.ok,forbidden)
  p.check('direct member cannot request on behalf of project',!forbiddenRequest.ok,forbiddenRequest)
  const requested=await tool('manager','request',{from:'alpha',target:'beta'})
  const req=rig.one("SELECT holder FROM ot.audience_requests WHERE requester='alpha' AND target='beta' AND status='pending' ORDER BY id DESC LIMIT 1")
  p.check('project request routes to target nearest real-agent superior',requested.ok&&req?.holder==='peer-manager',{requested,req})
  const decision=await tool('peer-manager','deny',{from:'alpha',target:'beta'})
  p.check('project superior can decide project audience request',decision.ok,decision)
  const requestUser=await tool('manager','request',{from:'alpha',target:'user'})
  const userReq=rig.one("SELECT holder FROM ot.audience_requests WHERE requester='alpha' AND target='@user' AND status='pending' ORDER BY id DESC LIMIT 1")
  p.check('project user-audience request waits on user',requestUser.ok&&userReq?.holder==='@user',{requestUser,userReq})
  const grantByAgent=await tool('boss','grant',{from:'alpha',target:'user'})
  p.check('agent tool grants user audience to a project in its subtree',grantByAgent.ok,grantByAgent)
  const revokeByAgent=await tool('boss','revoke',{grantee:'alpha',target:'user'})
  p.check('agent tool revokes project audience under current authority',revokeByAgent.ok,revokeByAgent)
  await rig.userMail('alpha','Synthetic actual user project contact')
  p.check('default user project message grants the project user audience',explicitCount('alpha')>=1&&rig.one("SELECT count(*)::int AS n FROM ot.audiences WHERE grantee='alpha' AND grantor='@user' AND revoked_at IS NULL AND NOT paused").n===1)
  p.check('system fair-queue nudge does not copy user audience to a member',explicitCount('member')===0&&explicitCount('nested-member')===0)
  await api('revoke','alpha','user')
  const broadcast=await rig.api('POST',`/api/orgs/${rig.org}/nodes/alpha/broadcast`,{text:'Synthetic project broadcast'}).then(json=>({ok:true,json}),e=>({ok:false,error:e.message}))
  p.check('broadcast grants the project user audience',broadcast.ok&&rig.one("SELECT count(*)::int AS n FROM ot.audiences WHERE grantee='alpha' AND grantor='@user' AND revoked_at IS NULL AND NOT paused").n===1,broadcast)
  p.check('project grants do not create project turns',rig.sql("SELECT 1 FROM ot.turns t JOIN ot.agents a ON a.id=t.agent_id WHERE a.kind='project'").length===0)
  return p.summary()
}
